#!/usr/bin/env python3
"""Regenerates iris/src/Repro/Production.cls from the CASES table.
The generated class is committed, so this script is a convenience, not a build step."""
import sys
from xml.sax.saxutils import quoteattr

DEFAULT_RCA = ":?R=RF,:?E=S,:~=S,:?A=C,:*=S,:I?=W,:T?=C"   # documented default
# (name, port, ReplyCodeActions or None for "left empty", comment)
CASES = [
    ("default",  29201, None,                                         "ReplyCodeActions left empty = documented default"),
    ("failrej",  29202, ":?R=F,:?E=S,:~=S,:?A=C,:*=S,:I?=W,:T?=C",    "Default, but AR/CR fail immediately instead of retrying"),
    ("legacy",   29203, ":?R=W,:?E=W,:~=F,:?A=C,:T?=C,:*=F",          "Inherited string: warns on AR/AE, fails on everything unknown"),
]

# Extra inbound services: same operations, different AckMode (what the SENDER gets back).
# (service name, port, AckMode, target operation)
EXTRA_SERVICES = [
    ("in.app.default", 29211, "App",   "out.default"),
    ("in.app.failrej", 29212, "App",   "out.failrej"),
    ("in.app.legacy",  29213, "App",   "out.legacy"),
    ("in.msh.failrej", 29214, "Msh",   "out.failrej"),
    ("in.never.failrej", 29215, "Never", "out.failrej"),
    ("in.byte.failrej", 29216, "Byte",  "out.failrej"),
]

out = ['''/// Lab production for the article "The ACK arrived - why is my HL7 message still retried?"
///
///   sender --MLLP--> [in.<case>] --> [out.<case>] --MLLP--> lab simulator (host "lab", port 6600)
///
/// One service/operation pair per ReplyCodeActions variant. Every operation uses the same
/// connection and retry settings, so the only variable between cases is ReplyCodeActions.
/// GENERATED by tools/gen_production.py - edit the CASES table there.
Class Repro.Production Extends Ens.Production
{

XData ProductionDefinition
{
<Production Name="Repro.Production" LogGeneralTraceEvents="false">
  <Description>HL7 ACK / ReplyCodeActions investigation lab</Description>
  <ActorPoolSize>1</ActorPoolSize>''']
for name, port, rca, comment in CASES:
    out.append(f'''
  <Item Name="in.{name}" ClassName="EnsLib.HL7.Service.TCPService" PoolSize="1" Enabled="true" LogTraceEvents="true" Comment="Receives from the sender and ACKs immediately">
    <Setting Target="Adapter" Name="Port">{port}</Setting>
    <Setting Target="Adapter" Name="JobPerConnection">1</Setting>
    <Setting Target="Host" Name="MessageSchemaCategory">2.5</Setting>
    <Setting Target="Host" Name="TargetConfigNames">out.{name}</Setting>
    <Setting Target="Host" Name="AckMode">Immed</Setting>
    <Setting Target="Host" Name="ArchiveIO">1</Setting>
  </Item>
  <Item Name="out.{name}" ClassName="EnsLib.HL7.Operation.TCPOperation" PoolSize="1" Enabled="true" LogTraceEvents="true" Comment={quoteattr(comment)}>
    <Setting Target="Adapter" Name="IPAddress">lab</Setting>
    <Setting Target="Adapter" Name="Port">6600</Setting>
    <Setting Target="Adapter" Name="ResponseTimeout">5</Setting>
    <Setting Target="Host" Name="RetryInterval">2</Setting>
    <Setting Target="Host" Name="FailureTimeout">10</Setting>''' + (f'''
    <Setting Target="Host" Name="ReplyCodeActions">{rca}</Setting>''' if rca else '') + '''
    <Setting Target="Host" Name="ArchiveIO">1</Setting>
  </Item>''')
for name, port, mode, target in EXTRA_SERVICES:
    out.append(f'''
  <Item Name="{name}" ClassName="EnsLib.HL7.Service.TCPService" PoolSize="1" Enabled="true" LogTraceEvents="true" Comment="AckMode={mode}: same operation, different answer to the sender">
    <Setting Target="Adapter" Name="Port">{port}</Setting>
    <Setting Target="Adapter" Name="JobPerConnection">1</Setting>
    <Setting Target="Host" Name="MessageSchemaCategory">2.5</Setting>
    <Setting Target="Host" Name="TargetConfigNames">{target}</Setting>
    <Setting Target="Host" Name="AckMode">{mode}</Setting>
    <Setting Target="Host" Name="ArchiveIO">1</Setting>
  </Item>''')
out.append('''</Production>
}

}
''')
open("iris/src/Repro/Production.cls", "w").write("\n".join(out).replace("\n\n  <Item", "\n  <Item", 0))
print("written", len(CASES), "cases")
